package tz_test

// Conformance tests for tz.Compile and tz.Load against RFC 5545 §3.6.5
// (VTIMEZONE) and §3.2.19 (TZID). Onset instants are worked out by hand:
// an onset written as local time T on an observance whose TZOFFSETFROM is
// F happens at T - F in UTC.

import (
	"errors"
	"testing"
	"time"

	"github.com/aanelson/iCalendar/civil"
	"github.com/aanelson/iCalendar/recur"
	"github.com/aanelson/iCalendar/tz"
)

const (
	est = -5 * 3600
	edt = -4 * 3600
)

func wall(s string) civil.DateTime {
	dt, err := civil.ParseDateTime(s)
	if err != nil {
		panic(err)
	}
	return dt
}

func rule(s string) recur.Rule {
	r, err := recur.ParseRule(s)
	if err != nil {
		panic(err)
	}
	return r
}

func utc(s string) time.Time {
	v, err := time.Parse(time.RFC3339, s)
	if err != nil {
		panic(err)
	}
	return v
}

func compile(t *testing.T, def tz.Definition) *time.Location {
	t.Helper()
	loc, err := tz.Compile(def)
	if err != nil {
		t.Fatalf("Compile(%s): %v", def.TZID, err)
	}
	return loc
}

// checkAt checks the offset (and, if not "", the abbreviation) at each
// instant.
func checkAt(t *testing.T, loc *time.Location, at string, off int, name string) {
	t.Helper()
	gotName, gotOff := utc(at).In(loc).Zone()
	if gotOff != off || name != "" && gotName != name {
		t.Errorf("%s at %s: %s %+d, want %s %+d", loc, at, gotName, gotOff, name, off)
	}
}

// §3.6.5: "If observance is known to have an effective end date, the
// UNTIL recurrence rule parameter MUST be used to specify the last valid
// onset of this observance (i.e., the UNTIL DATE-TIME will be equal to the
// last instance generated by the recurrence pattern). It MUST be specified
// in UTC time." The UNTIL is an instant, compared with each onset's
// instant (local 02:00 at TZOFFSETFROM -0500, so 07:00Z). One second
// short of the 2002 onset excludes it; equal to it includes it.
func TestConformanceObservanceUntilIsAnInstant(t *testing.T) {
	for _, tt := range []struct {
		until  string
		in2002 int // the offset in summer 2002
	}{
		{"20020407T065959Z", est},
		{"20020407T070000Z", edt},
	} {
		loc := compile(t, tz.Definition{TZID: "Until " + tt.until, Observances: []tz.Observance{
			{Daylight: true, Start: wall("2000-04-02T02:00:00"), OffsetFrom: est, OffsetTo: edt, Name: "EDT",
				Rules: []recur.Rule{rule("FREQ=YEARLY;BYMONTH=4;BYDAY=1SU;UNTIL=" + tt.until)}},
			{Start: wall("2000-10-29T02:00:00"), OffsetFrom: edt, OffsetTo: est, Name: "EST",
				Rules: []recur.Rule{rule("FREQ=YEARLY;BYMONTH=10;BYDAY=-1SU")}},
		}})
		checkAt(t, loc, "2001-07-01T12:00:00Z", edt, "EDT")
		checkAt(t, loc, "2002-07-01T12:00:00Z", tt.in2002, "")
		checkAt(t, loc, "2003-07-01T12:00:00Z", est, "EST")
	}
}

// §3.6.5: "TZOFFSETFROM is combined with DTSTART to define the effective
// onset", and RDATE "MUST be specified as a date with local time value,
// relative to the UTC offset specified in the TZOFFSETFROM property."
// Standard time starting at 02:00 with TZOFFSETFROM -0400 begins at
// 06:00Z (not 07:00Z, which TZOFFSETTO would give); daylight time at
// 02:00 with TZOFFSETFROM -0500 begins at 07:00Z (not 06:00Z).
func TestConformanceObservanceOnsetUsesOffsetFrom(t *testing.T) {
	loc := compile(t, tz.Definition{TZID: "Onsets", Observances: []tz.Observance{
		{Start: wall("2000-10-29T02:00:00"), OffsetFrom: edt, OffsetTo: est, Name: "EST",
			RDates: []civil.DateTime{wall("2001-10-28T02:00:00")}},
		{Daylight: true, Start: wall("2001-04-01T02:00:00"), OffsetFrom: est, OffsetTo: edt, Name: "EDT"},
	}})
	checkAt(t, loc, "2000-10-29T05:59:59Z", edt, "")
	checkAt(t, loc, "2000-10-29T06:00:00Z", est, "EST")
	checkAt(t, loc, "2001-04-01T06:59:59Z", est, "EST")
	checkAt(t, loc, "2001-04-01T07:00:00Z", edt, "EDT")
	checkAt(t, loc, "2001-10-28T05:59:59Z", edt, "EDT")
	checkAt(t, loc, "2001-10-28T06:00:00Z", est, "EST")
}

// §3.6.5: "The offset to apply at any given time is found by locating the
// observance that has the last onset date and time before the time in
// question, and using the offset value from that observance." That holds
// whatever order the sub-components are written in, and when only the
// name changes. TZNAME is "the customary name for the time zone" in that
// observance (§3.6.5, §3.8.3.2).
func TestConformanceObservanceOrderAndNames(t *testing.T) {
	obs := []tz.Observance{
		{Start: wall("2010-01-01T00:00:00"), OffsetFrom: 3600, OffsetTo: 3600, Name: "BBB"},
		{Start: wall("2020-01-01T00:00:00"), OffsetFrom: 3600, OffsetTo: 7200, Name: "CCC"},
		{Start: wall("2000-01-01T00:00:00"), OffsetFrom: 3600, OffsetTo: 3600, Name: "AAA"},
	}
	loc := compile(t, tz.Definition{TZID: "Names", Observances: obs})
	checkAt(t, loc, "2005-06-01T00:00:00Z", 3600, "AAA")
	checkAt(t, loc, "2009-12-31T22:59:59Z", 3600, "AAA")
	checkAt(t, loc, "2009-12-31T23:00:00Z", 3600, "BBB")
	checkAt(t, loc, "2019-12-31T22:59:59Z", 3600, "BBB")
	checkAt(t, loc, "2019-12-31T23:00:00Z", 7200, "CCC")
	checkAt(t, loc, "2150-06-01T00:00:00Z", 7200, "CCC")
}

// Before the first onset the RFC is silent. The documented choice
// (tz.Compile): "the zone keeps the first observance's OffsetFrom". With
// the observances written out of onset order, "first" is checked to mean
// the earliest onset (+0100 here, the 2000 observance's TZOFFSETFROM),
// not the first written (+0300).
func TestConformanceBeforeFirstOnset(t *testing.T) {
	loc := compile(t, tz.Definition{TZID: "Before", Observances: []tz.Observance{
		{Start: wall("2010-01-01T00:00:00"), OffsetFrom: 3 * 3600, OffsetTo: 2 * 3600, Name: "LATE"},
		{Start: wall("2000-01-01T00:00:00"), OffsetFrom: 3600, OffsetTo: 3 * 3600, Name: "EARLY"},
	}})
	checkAt(t, loc, "1990-06-01T00:00:00Z", 3600, "")
	checkAt(t, loc, "1999-12-31T22:59:59Z", 3600, "")
	checkAt(t, loc, "1999-12-31T23:00:00Z", 3*3600, "EARLY")
	name, _ := utc("1990-06-01T00:00:00Z").In(loc).Zone()
	t.Logf("abbreviation before the first onset: %q", name)
}

// §3.3.14: UTC-OFFSET may carry seconds ("utc-offset = time-numzone",
// "+" / "-" time-hour time-minute [time-second]). A historical offset of
// +00:19:32 is kept to the second.
func TestConformanceOffsetSeconds(t *testing.T) {
	const off = 19*60 + 32
	loc := compile(t, tz.Definition{TZID: "Amsterdam 1930", Observances: []tz.Observance{
		{Start: wall("1900-01-01T00:00:00"), OffsetFrom: off, OffsetTo: off, Name: "AMT"},
	}})
	checkAt(t, loc, "1930-06-01T00:00:00Z", off, "AMT")
}

// §3.6.5: a VTIMEZONE needs "at least one definition of a STANDARD or
// DAYLIGHT sub-component"; with none there is no offset at all, so
// Compile must fail rather than pick one.
func TestConformanceCompileEmpty(t *testing.T) {
	loc, err := tz.Compile(tz.Definition{TZID: "Empty"})
	if err == nil {
		t.Fatalf("Compile with no observances = %v, nil", loc)
	}
	if !errors.Is(err, tz.ErrInvalidDefinition) {
		t.Errorf("error %v doesn't wrap ErrInvalidDefinition", err)
	}
}

// The compiled location is named after the TZID, so a time shows which
// VTIMEZONE it came from.
func TestConformanceCompileName(t *testing.T) {
	loc := compile(t, tz.Definition{TZID: "Customized Time Zone", Observances: []tz.Observance{
		{Start: wall("1601-01-01T00:00:00"), OffsetFrom: 3600, OffsetTo: 3600},
	}})
	if loc.String() != "Customized Time Zone" {
		t.Errorf("name %q", loc.String())
	}
}

// §3.2.19: "An individual VTIMEZONE calendar component MUST be specified
// for each unique TZID parameter value". Without one, Load is the
// documented fallback, and it never guesses: a name it doesn't know is an
// error, and "Local" (the host's zone) and "" are refused.
func TestConformanceLoadNeverGuesses(t *testing.T) {
	for _, name := range []string{"Nowhere/Imaginary", "Local", "", "Eastern Time", "(UTC-05:00) Eastern Time (US & Canada)", "../../etc/localtime"} {
		loc, err := tz.Load(name)
		if err == nil {
			t.Errorf("Load(%q) = %v, nil; want an error", name, loc)
		} else if !errors.Is(err, tz.ErrUnknownZone) {
			t.Errorf("Load(%q): %v doesn't wrap ErrUnknownZone", name, err)
		}
	}
}
