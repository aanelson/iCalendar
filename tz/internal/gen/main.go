// Command gen writes tz/windows_gen.go, the Windows→IANA time zone table,
// from the Unicode CLDR file common/supplemental/windowsZones.xml.
//
// CLDR spells some zones with names IANA has since retired (Asia/Calcutta,
// Europe/Kiev, …). The generator rewrites those using the tzdb "backward"
// file: a name is an alias when backward makes it a Link and zone.tab no
// longer lists it as a country's zone. Names that tzdb merged into another
// zone but zone.tab still lists for their country (Europe/Amsterdam,
// Atlantic/Reykjavik) are current, so they are kept.
//
// Each input is downloaded unless a local path is given:
//
//	go run ./internal/gen [-in windowsZones.xml] [-dtd ldmlSupplemental.dtd]
//	    [-backward backward] [-zonetab zone.tab] [-o windows_gen.go]
//
// The output depends only on the input contents, so regenerating from the
// same files is byte-for-byte identical.
package main

import (
	"bufio"
	"bytes"
	"crypto/sha256"
	"encoding/hex"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"maps"
	"net/http"
	"os"
	"regexp"
	"slices"
	"strconv"
	"strings"
	"time"
)

const (
	cldrBase = "https://raw.githubusercontent.com/unicode-org/cldr/"
	tzBase   = "https://raw.githubusercontent.com/eggert/tz/"
)

// knownAliases are spot checks on the alias table built from backward. They
// are not the source of truth; they catch a parse that silently misses links.
var knownAliases = map[string]string{
	"America/Buenos_Aires": "America/Argentina/Buenos_Aires",
	"America/Godthab":      "America/Nuuk",
	"America/Indianapolis": "America/Indiana/Indianapolis",
	"Asia/Calcutta":        "Asia/Kolkata",
	"Asia/Katmandu":        "Asia/Kathmandu",
	"Asia/Rangoon":         "Asia/Yangon",
	"Asia/Saigon":          "Asia/Ho_Chi_Minh",
	"Asia/Thimbu":          "Asia/Thimphu",
	"Europe/Kiev":          "Europe/Kyiv",
	"Pacific/Truk":         "Pacific/Chuuk",
	"US/Eastern":           "America/New_York",
}

// cldrSpellings overrides backward for CLDR names that CLDR and tzdb resolve
// to different places. CLDR keeps America/Coral_Harbour as its name for
// Atikokan, Ontario; tzdb links it to America/Panama, which would give a
// Canadian entry a Panamanian name.
var cldrSpellings = map[string]string{
	"America/Coral_Harbour": "America/Atikokan",
}

func main() {
	log.SetFlags(0)
	log.SetPrefix("gen: ")
	var (
		in       = flag.String("in", "", "path to CLDR windowsZones.xml (default: download)")
		dtd      = flag.String("dtd", "", "path to CLDR ldmlSupplemental.dtd, for the CLDR version (default: download)")
		backward = flag.String("backward", "", "path to the tzdb backward file (default: download)")
		zonetab  = flag.String("zonetab", "", "path to the tzdb zone.tab file (default: download)")
		cldrRef  = flag.String("cldr-ref", "main", "unicode-org/cldr git ref to download from")
		tzRef    = flag.String("tz-ref", "main", "eggert/tz git ref to download from")
		out      = flag.String("o", "windows_gen.go", "output file")
	)
	flag.Parse()

	xmlData := input(*in, cldrBase+*cldrRef+"/common/supplemental/windowsZones.xml")
	dtdData := input(*dtd, cldrBase+*cldrRef+"/common/dtd/ldmlSupplemental.dtd")
	backData := input(*backward, tzBase+*tzRef+"/backward")
	tabData := input(*zonetab, tzBase+*tzRef+"/zone.tab")

	cldrVersion, err := parseCLDRVersion(dtdData)
	check(err)
	doc, err := parseWindowsZones(xmlData)
	check(err)
	aliases, err := parseAliases(backData, tabData)
	check(err)
	for alias, want := range knownAliases {
		if got := aliases[alias]; got != want {
			log.Fatalf("backward: alias %s resolves to %q, want %q", alias, got, want)
		}
	}

	t, err := build(doc, aliases)
	check(err)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by tz/internal/gen; DO NOT EDIT.\n\n")
	fmt.Fprintf(&b, "// Source: Unicode CLDR %s common/supplemental/windowsZones.xml", cldrVersion)
	if rev := doc.Version.Number; rev != "" && !strings.Contains(rev, "$Revision$") {
		fmt.Fprintf(&b, " %s", strings.Trim(rev, "$ "))
	}
	fmt.Fprintf(&b, "\n// (mapTimezones otherVersion=%q typeVersion=%q, sha256 %s).\n",
		doc.Map.OtherVersion, doc.Map.TypeVersion, digest(xmlData))
	fmt.Fprintf(&b, "// IANA aliases canonicalized with tzdb backward (sha256 %s)\n", digest(backData))
	fmt.Fprintf(&b, "// and zone.tab (sha256 %s).\n\n", digest(tabData))
	b.WriteString("package tz\n\n")

	b.WriteString(`// windowsZones maps a Windows time zone ID, as Outlook and Exchange write it in TZID
// (e.g. "Eastern Standard Time"), to the IANA zone CLDR gives for territory "001".
var windowsZones = map[string]string{
`)
	writeEntries(&b, t.world)
	b.WriteString("}\n\n")
	b.WriteString(`// windowsZonesByTerritory maps "WindowsID/TERRITORY" (e.g. "Eastern Standard Time/CA")
// to that territory's first IANA zone, for callers that know a region.
// Territory "001" is omitted: its zone is the one in windowsZones.
var windowsZonesByTerritory = map[string]string{
`)
	writeEntries(&b, t.byTerritory)
	b.WriteString("}\n")

	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatalf("formatting output: %v\n%s", err, b.Bytes())
	}
	check(os.WriteFile(*out, src, 0o644))

	renamed := slices.Sorted(maps.Keys(t.renamed))
	log.Printf("wrote %s: CLDR %s, %d Windows IDs, %d territory entries, %d aliases canonicalized",
		*out, cldrVersion, len(t.world), len(t.byTerritory), len(renamed))
	for _, old := range renamed {
		log.Printf("  %s -> %s", old, t.renamed[old])
	}
}

// input reads path, or downloads url when path is empty.
func input(path, url string) []byte {
	if path != "" {
		data, err := os.ReadFile(path)
		check(err)
		return data
	}
	client := &http.Client{Timeout: time.Minute}
	resp, err := client.Get(url)
	check(err)
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("GET %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(io.LimitReader(resp.Body, 16<<20))
	check(err)
	return data
}

type supplementalData struct {
	Version struct {
		Number string `xml:"number,attr"`
	} `xml:"version"`
	Map struct {
		OtherVersion string    `xml:"otherVersion,attr"`
		TypeVersion  string    `xml:"typeVersion,attr"`
		Zones        []mapZone `xml:"mapZone"`
	} `xml:"windowsZones>mapTimezones"`
}

type mapZone struct {
	Other     string `xml:"other,attr"`
	Territory string `xml:"territory,attr"`
	Type      string `xml:"type,attr"`
}

func parseWindowsZones(data []byte) (*supplementalData, error) {
	var doc supplementalData
	if err := xml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("windowsZones.xml: %v", err)
	}
	if len(doc.Map.Zones) == 0 {
		return nil, fmt.Errorf("windowsZones.xml: no mapZone elements")
	}
	return &doc, nil
}

var cldrVersionRE = regexp.MustCompile(`<!ATTLIST\s+version\s+cldrVersion\s+CDATA\s+#FIXED\s+"([^"]+)"`)

func parseCLDRVersion(dtd []byte) (string, error) {
	m := cldrVersionRE.FindSubmatch(dtd)
	if m == nil {
		return "", fmt.Errorf("ldmlSupplemental.dtd: no cldrVersion attribute")
	}
	return string(m[1]), nil
}

// parseAliases returns every retired zone name in backward mapped to the
// current name for the same place. A Link whose name zone.tab still lists is
// a current zone, not an alias. A "#= TARGET1" comment names the place's own
// zone where backward had to point at a merged one (Pacific/Truk #=
// Pacific/Chuuk), so it is preferred over the Link target.
func parseAliases(backward, zonetab []byte) (map[string]string, error) {
	current := make(map[string]bool)
	sc := bufio.NewScanner(bytes.NewReader(zonetab))
	for sc.Scan() {
		line := sc.Text()
		if line == "" || line[0] == '#' {
			continue
		}
		f := strings.Split(line, "\t")
		if len(f) < 3 {
			return nil, fmt.Errorf("zone.tab: malformed line %q", line)
		}
		current[f[2]] = true
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}
	if len(current) < 100 {
		return nil, fmt.Errorf("zone.tab: only %d zones", len(current))
	}

	next := make(map[string]string) // alias -> next name toward the current one
	sc = bufio.NewScanner(bytes.NewReader(backward))
	for sc.Scan() {
		data, comment, _ := strings.Cut(sc.Text(), "#")
		f := strings.Fields(data)
		if len(f) == 0 || f[0] != "Link" {
			continue
		}
		if len(f) != 3 {
			return nil, fmt.Errorf("backward: malformed line %q", sc.Text())
		}
		target, name := f[1], f[2]
		if current[name] {
			continue
		}
		if hint, ok := strings.CutPrefix(comment, "="); ok {
			if h := strings.Fields(hint); len(h) > 0 {
				target = h[0]
			}
		}
		next[name] = target
	}
	if err := sc.Err(); err != nil {
		return nil, err
	}

	aliases := make(map[string]string, len(next))
	for name := range next {
		z := name
		for i := 0; ; i++ {
			n, ok := next[z]
			if !ok {
				break
			}
			if i == len(next) {
				return nil, fmt.Errorf("backward: link cycle through %s", name)
			}
			z = n
		}
		aliases[name] = z
	}
	return aliases, nil
}

// entry is one table value: the IANA zone, and CLDR's spelling of it when
// that was an alias.
type entry struct {
	zone, cldr string
}

type table struct {
	world       map[string]entry  // Windows ID -> zone for territory 001
	byTerritory map[string]entry  // "Windows ID/TERRITORY" -> zone
	renamed     map[string]string // CLDR spelling -> zone written instead
}

func build(doc *supplementalData, aliases map[string]string) (*table, error) {
	t := &table{
		world:       make(map[string]entry),
		byTerritory: make(map[string]entry),
		renamed:     make(map[string]string),
	}
	ids := make(map[string]bool)
	for _, z := range doc.Map.Zones {
		names := strings.Fields(z.Type)
		if z.Other == "" || z.Territory == "" || len(names) == 0 {
			return nil, fmt.Errorf("windowsZones.xml: incomplete mapZone %+v", z)
		}
		e := entry{zone: names[0]}
		if c, ok := cldrSpellings[e.zone]; ok {
			t.renamed[e.zone] = c
			e = entry{zone: c, cldr: e.zone}
		} else if c, ok := aliases[e.zone]; ok {
			t.renamed[e.zone] = c
			e = entry{zone: c, cldr: e.zone}
		}
		if err := validZone(e.zone); err != nil {
			return nil, fmt.Errorf("windowsZones.xml: %q (%s): %v", z.Other, z.Territory, err)
		}
		if _, ok := aliases[e.zone]; ok {
			return nil, fmt.Errorf("windowsZones.xml: %q (%s): %s is still an alias", z.Other, z.Territory, e.zone)
		}
		ids[z.Other] = true
		m, key := t.byTerritory, z.Other+"/"+z.Territory
		if z.Territory == "001" {
			m, key = t.world, z.Other
		}
		if _, dup := m[key]; dup {
			return nil, fmt.Errorf("windowsZones.xml: duplicate mapZone for %q territory %s", z.Other, z.Territory)
		}
		m[key] = e
	}
	for id := range ids {
		if _, ok := t.world[id]; !ok {
			return nil, fmt.Errorf("windowsZones.xml: %q has no territory 001 entry", id)
		}
	}
	return t, nil
}

var zoneNameRE = regexp.MustCompile(`^[A-Za-z][A-Za-z0-9_+-]*(/[A-Za-z0-9][A-Za-z0-9_+-]*)*$`)

func validZone(z string) error {
	switch {
	case z == "":
		return fmt.Errorf("empty IANA zone")
	case !strings.Contains(z, "/") && z != "UTC":
		return fmt.Errorf("IANA zone %q is neither Area/Location, Etc/…, nor UTC", z)
	case !zoneNameRE.MatchString(z):
		return fmt.Errorf("malformed IANA zone %q", z)
	}
	return nil
}

// writeEntries writes m as sorted map literal lines, noting CLDR's spelling
// of any zone that was canonicalized.
func writeEntries(b *bytes.Buffer, m map[string]entry) {
	for _, k := range slices.Sorted(maps.Keys(m)) {
		e := m[k]
		fmt.Fprintf(b, "\t%s: %s,", strconv.Quote(k), strconv.Quote(e.zone))
		if e.cldr != "" {
			fmt.Fprintf(b, " // CLDR: %s", e.cldr)
		}
		b.WriteByte('\n')
	}
}

func digest(data []byte) string {
	sum := sha256.Sum256(data)
	return hex.EncodeToString(sum[:8])
}

func check(err error) {
	if err != nil {
		log.Fatal(err)
	}
}
